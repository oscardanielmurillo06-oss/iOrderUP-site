  function detectLang() {
    try {
      var stored = localStorage.getItem(STORAGE_KEY);
      if (stored && SUPPORTED.indexOf(stored) !== -1) return stored;
    } catch (e) {}
    var nav = (navigator.language || (navigator.languages && navigator.languages[0]) || "").toLowerCase();
    if (nav.indexOf("es") === 0) return "es";
    if (nav.indexOf("pt") === 0) return "pt";
    return DEFAULT_LANG;
  }

  function t(key) {
    var lang = I18N.currentLang;
    var value = DICT[lang] && DICT[lang][key];
    if (value === undefined) value = DICT[DEFAULT_LANG][key];
    return value === undefined ? "" : value;
  }

  function applyLang(lang) {
    if (SUPPORTED.indexOf(lang) === -1) lang = DEFAULT_LANG;
    I18N.currentLang = lang;
    document.documentElement.setAttribute("lang", lang);

    document.querySelectorAll("[data-i18n]").forEach(function (el) {
      var value = t(el.getAttribute("data-i18n"));
      if (value) el.textContent = value;
    });
    document.querySelectorAll("[data-i18n-aria]").forEach(function (el) {
      var value = t(el.getAttribute("data-i18n-aria"));
      if (value) el.setAttribute("aria-label", value);
    });
    document.querySelectorAll("[data-i18n-placeholder]").forEach(function (el) {
      var value = t(el.getAttribute("data-i18n-placeholder"));
      if (value) el.setAttribute("placeholder", value);
    });
    document.querySelectorAll(".lang-btn").forEach(function (btn) {
      var isActive = btn.getAttribute("data-lang") === lang;
      btn.setAttribute("aria-pressed", isActive ? "true" : "false");
      btn.classList.toggle("is-active", isActive);
    });

    try { localStorage.setItem(STORAGE_KEY, lang); } catch (e) {}
  }

  var I18N = {
    currentLang: DEFAULT_LANG,
    supported: SUPPORTED,
    t: t,
    setLang: applyLang,
  };
  window.IORDERUP_I18N = I18N;

  applyLang(detectLang());

  document.querySelectorAll(".lang-btn").forEach(function (btn) {
    btn.addEventListener("click", function () {
      applyLang(btn.getAttribute("data-lang"));
    });
  });
